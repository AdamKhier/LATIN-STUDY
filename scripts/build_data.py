#!/usr/bin/env python3
"""Parse the paradigm markdown files in latin_pronoun_tables/ into src/data.js.

The markdown files are the source of truth: edit them, then re-run

    python3 scripts/build_data.py
"""

from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "latin_pronoun_tables"
OUTPUT = ROOT / "src" / "data.js"

GENDERS = ["Masculine", "Feminine", "Neuter"]
EXPECTED_CASES = ["Nominative", "Genitive", "Dative", "Accusative", "Ablative"]


def parse_file(path: pathlib.Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()

    title = ""
    kind = ""
    meaning = ""
    for line in lines:
        stripped = line.strip()
        if not title and stripped.startswith("# "):
            title = stripped[2:].strip()
            continue
        match = re.fullmatch(r"\*(?!\*)(.+?)\*", stripped)
        if match:
            label = match.group(1)
            if ":" in label:
                kind, meaning = (part.strip() for part in label.split(":", 1))
            else:
                meaning = label
            break

    if not title:
        raise ValueError(f"{path}: no '# Title' heading found")

    sections: dict[str, list[dict]] = {}
    number = None
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("## "):
            number = stripped[3:].strip().lower()
            sections[number] = []
            continue
        if number and stripped.startswith("|"):
            cells = [cell.strip() for cell in stripped.strip("|").split("|")]
            if cells[0].lower() == "case" or set(cells[0]) <= {"-", ":", " "}:
                continue
            if len(cells) != 1 + len(GENDERS):
                raise ValueError(f"{path}: expected 4 columns, got {cells}")
            case, *forms = cells
            sections[number].append(
                {"case": case, "forms": dict(zip((g.lower() for g in GENDERS), forms))}
            )

    for number, rows in sections.items():
        cases = [row["case"] for row in rows]
        if cases != EXPECTED_CASES:
            raise ValueError(f"{path}: unexpected cases in {number}: {cases}")

    if sorted(sections) != ["plural", "singular"]:
        raise ValueError(f"{path}: expected singular and plural sections")

    return {
        "id": path.stem,
        "title": title,
        "kind": kind,
        "meaning": meaning,
        "singular": sections["singular"],
        "plural": sections["plural"],
    }


def main() -> None:
    files = sorted(SOURCE_DIR.glob("*.md"))
    if not files:
        raise SystemExit(f"no markdown tables found in {SOURCE_DIR}")

    paradigms = [parse_file(path) for path in files]
    total = sum(len(p["singular"]) + len(p["plural"]) for p in paradigms) * len(GENDERS)

    body = json.dumps(paradigms, indent=2, ensure_ascii=False)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by scripts/build_data.py from latin_pronoun_tables/*.md\n"
        "// Do not edit by hand: change the markdown and re-run the script.\n"
        f"// {len(paradigms)} paradigms, {total} forms.\n\n"
        f"export const PARADIGMS = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(paradigms)} paradigms, {total} forms")


if __name__ == "__main__":
    main()
